CREATE TABLE crawler_execution_history (
    run_id VARCHAR(36) PRIMARY KEY,
    category VARCHAR(20) NOT NULL,
    source_name VARCHAR(60) NOT NULL,
    trigger_type VARCHAR(20) NOT NULL,
    operation VARCHAR(20) NOT NULL,
    stage VARCHAR(20) NOT NULL,
    region_scope VARCHAR(20) NOT NULL,
    region_count INT NOT NULL DEFAULT 0,
    deal_ymd VARCHAR(6) NOT NULL DEFAULT '',
    started_at DATETIME(6) NOT NULL,
    finished_at DATETIME(6) NULL,
    last_seen_at DATETIME(6) NOT NULL,
    status VARCHAR(20) NOT NULL,
    collected_count INT NOT NULL DEFAULT 0,
    inserted_count INT NOT NULL DEFAULT 0,
    updated_count INT NOT NULL DEFAULT 0,
    error_count INT NOT NULL DEFAULT 0,
    skipped_count INT NOT NULL DEFAULT 0,
    failed_regions INT NOT NULL DEFAULT 0,
    reused_batches INT NOT NULL DEFAULT 0,
    last_seq BIGINT NOT NULL,
    KEY idx_execution_category_started(category,started_at)
);
